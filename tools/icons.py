# Generates weather_icons.h (python3 tools/icons.py > weather_icons.h): 14x16 icons, one uint16_t per row, bit 15 = leftmost column
import sys
W, H = 14, 16

def blank(): return [[0]*W for _ in range(H)]
def put(img, art, top, left=0):
    for r, line in enumerate(art):
        for c, ch in enumerate(line):
            if ch == '#': img[top+r][left+c] = 1

CLOUD = [
 ".....####.....",
 "....#....#....",
 "..##......##..",
 ".#..........#.",
 "#............#",
 "#............#",
 ".############.",
]
SUN = [
 "......#......",
 "..#.......#..",
 "...#.....#...",
 ".....###.....",
 "....#####....",
 "...#######...",
 "##.#######.##",
 "...#######...",
 "....#####....",
 ".....###.....",
 "...#.....#...",
 "..#.......#..",
 "......#......",
]
SMALL_SUN = [
 "...#...",
 ".#...#.",
 "..###..",
 "#.###.#",
 "..###..",
 ".#...#.",
 "...#...",
]

def cloud_over(img, top, left=0):
    # Clear the cloud's inside, then draw its outline
    for r, line in enumerate(CLOUD):
        cols = [c for c, ch in enumerate(line) if ch == '#']
        for c in range(min(cols), max(cols)+1):
            img[top+r][left+c] = 0
    put(img, CLOUD, top, left)

icons = {}
i = blank(); put(i, SUN, 1); icons['SUN'] = i
i = blank(); put(i, SMALL_SUN, 1, 7); cloud_over(i, 6); icons['PARTLY'] = i
i = blank(); cloud_over(i, 4); icons['CLOUD'] = i
i = blank(); cloud_over(i, 1); put(i, [
 "...#...#...#..",
 "..#...#...#...",
 "..............",
 ".....#...#....",
 "....#...#.....",
], 9); icons['RAIN'] = i
i = blank(); cloud_over(i, 1); put(i, [
 "..#....#....#.",
 "..............",
 "....#....#....",
 "..............",
 "..#....#....#.",
], 9); icons['SNOW'] = i
i = blank(); cloud_over(i, 1); put(i, [
 "......##......",
 ".....##.......",
 "....#####.....",
 ".......##.....",
 "......##......",
 ".....#........",
], 8); icons['STORM'] = i
i = blank(); put(i, [
 ".###########..",
 "..............",
 "..###########.",
 "..............",
 ".###########..",
 "..............",
 "..###########.",
 "..............",
 ".###########..",
], 3); icons['FOG'] = i

if sys.argv[1:] == ['preview']:
    names = list(icons)
    for r in range(H):
        print('  '.join(''.join('#' if p else '.' for p in icons[n][r]) for n in names))
    print('  '.join(n.ljust(W) for n in names))
else:
    print("// weather_icons.h - generated by tools/icons.py, 14x16 px, bit 15 = leftmost column")
    print("#ifndef WEATHER_ICONS_H\n#define WEATHER_ICONS_H\n\n#include <stdint.h>\n")
    print("enum WeatherIcon { " + ", ".join("ICON_" + n for n in icons) + ", ICON_COUNT };\n")
    print("static const uint16_t WEATHER_ICONS[ICON_COUNT][16] = {")
    for n, img in icons.items():
        rows = ["0x%04X" % sum(p << (15-c) for c, p in enumerate(row)) for row in img]
        print("  { // %s\n    %s },"% (n, ", ".join(rows)))
    print("};\n\n#endif")
